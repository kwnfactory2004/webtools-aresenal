export const GLYPH_W = W;
export const GLYPH_H = H;
export const GLYPHS = Object.freeze(Object.fromEntries(Object.entries(RAW).map(([k, rows]) => [k, Object.freeze(rows.slice())])));

const has = (c) => Object.prototype.hasOwnProperty.call(GLYPHS, c);
// 1文字を、対応している形に（小文字は大文字に）。対応していなければ null
function norm(c) {
  if (has(c)) return c;
  const u = c.toUpperCase();
  return u.length === c.length && has(u) ? u : null;
}

function esc(text) {
  return String(text ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// 全文字がドット文字で出せるか（空文字は false）
export function supportsDot(text) {
  const chars = Array.from(String(text ?? ''));
  return chars.length > 0 && chars.every((c) => norm(c) !== null);
}

// 点の位置（列 x・行 y）。文字の間は1列あける。対応していない文字は空白として扱う（落ちない）
export function layoutDots(text) {
  const chars = Array.from(String(text ?? ''));
  const n = chars.length;
  const dots = [];
  chars.forEach((c, i) => {
    const g = GLYPHS[norm(c) || ' '];
    const ox = i * (W + 1);
    for (let y = 0; y < H; y++) {
      for (let x = 0; x < W; x++) if (g[y][x] === '#') dots.push({ x: ox + x, y });
    }
  });
  return { cols: n > 0 ? n * W + (n - 1) : 0, rows: H, dots };
}

// 数を短く書く（0.4 → .4、-0.8 → -.8）
const num = (v) => String(+v.toFixed(3)).replace(/^(-?)0\./, '$1.');

// 点（中心 x+.5, y+.5、直径 d）を、半円の弧2つで描く1本の d 文字列にまとめる。
// 最初の点だけ絶対位置（M）、あとは前の点からの差（m）。弧2つで元の位置に戻るので、差は整数になる
function dotsPath(dots, d) {
  const r = Math.min(0.5, Math.max(0.05, Number(d) / 2 || 0.4));
  const arc = `a${num(r)} ${num(r)} 0 1 0 ${num(2 * r)} 0a${num(r)} ${num(r)} 0 1 0-${num(2 * r)} 0`;
  let prev = null;
  return dots.map((p) => {
    const head = prev ? `m${p.x - prev.x} ${p.y - prev.y}` : `M${num(p.x + 0.5 - r)} ${num(p.y + 0.5)}`;
    prev = p;
    return head + arc;
  }).join('');
}

// ドット文字の SVG。opts: { dot: 点の直径（1マス=1。既定 0.8）, className, decorative: true なら読み上げない（aria-hidden） }
export function dotSvg(text, opts = {}) {
  const { dot = 0.8, className = '', decorative = false } = opts || {};
  const lay = layoutDots(text);
  const cls = ['dot', className].filter(Boolean).join(' ');
  const a11y = decorative ? 'aria-hidden="true"' : `role="img" aria-label="${esc(text)}"`;
  return `<svg class="${esc(cls)}" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${Math.max(1, lay.cols)} ${lay.rows}" fill="currentColor" focusable="false" ${a11y}><path d="${dotsPath(lay.dots, dot)}"></path></svg>`;
}

// 全文字が対応していればドット文字、1つでも未対応（日本語など）なら普通の文字。どちらも全文を1回だけ読ませる。
// opts.words = true: 単語ごとに別の SVG にして、幅が足りないときに単語の切れ目で折り返せるようにする（読み上げは外側の1回）
export function dotText(text, opts = {}) {
  const o = opts || {};
  const t = String(text ?? '');
  const cls = esc(o.className || '');
  if (!t.trim()) return ''; // 空・空白だけ: 何も出さない（中身の無い role="img" を作らない）
  if (!supportsDot(t)) {
    return `<span class="dot-fallback${cls ? ' ' + cls : ''}" role="img" aria-label="${esc(t)}">${esc(t)}</span>`;
  }
  if (o.words) {
    const words = t.split(/ +/).filter(Boolean);
    if (words.length === 0) return ''; // 空白だけ: 中身の無い role="img" を作らない
    const inner = words.map((w) => dotSvg(w, { dot: o.dot, decorative: true })).join('');
    return `<span class="dot-words${cls ? ' ' + cls : ''}" role="img" aria-label="${esc(t)}">${inner}</span>`;
  }
  return dotSvg(t, { dot: o.dot, className: o.className });
}

