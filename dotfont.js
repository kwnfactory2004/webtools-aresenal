export function iconDots(name) {
  const rows = Object.prototype.hasOwnProperty.call(DOT_ICONS, name) ? DOT_ICONS[name] : [];
  const dots = [];
  rows.forEach((row, y) => Array.from(row).forEach((c, x) => { if (c === '#') dots.push({ x, y }); }));
  return dots;
}

